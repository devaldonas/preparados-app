// 🔥 FUNÇÃO PARA BUSCAR DESCRIÇÃO POR NOME
export function getDescricaoItem(nome: string): string | undefined {
  // Busca exata pelo nome
  if (descricoesMochila[nome]) {
    return descricoesMochila[nome]
  }
  
  // Busca ignorando caracteres especiais (parênteses, etc)
  const nomeLimpo = nome.replace(/[\(\)]/g, '').trim()
  for (const [key, value] of Object.entries(descricoesMochila)) {
    const keyLimpo = key.replace(/[\(\)]/g, '').trim()
    if (keyLimpo === nomeLimpo) {
      return value
    }
  }
  
  return undefined
}